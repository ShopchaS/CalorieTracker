int WorkoutCalculator::calculateDailyCalories(const User& u) {
    double bmr = (u.gender == 'M') 
        ? (10 * u.weight + 6.25 * u.height - 5 * u.age + 5)
        : (10 * u.weight + 6.25 * u.height - 5 * u.age - 161);
    return static_cast<int>(bmr * u.activity_level);
}

QString WorkoutCalculator::generateDynamicPlan(int goal, int sleep, int cals, int meal, const QDate& date, bool isAuto, const QStringList& manualGroups) {
    QString plan = "";
    int readiness = 100;
    
    if (sleep < 5) readiness -= 40;
    else if (sleep < 7) readiness -= 20;
    
    if (cals < 1200) readiness -= 30;
    else if (cals < 1800) readiness -= 15;
    
    if (meal == 0) readiness -= 20; 
    if (meal > 5) readiness -= 15;  

    readiness = std::max(0, std::min(100, readiness));

    plan += "Состояние\n";
    plan += QString("Индекс готовности к нагрузкам: %1%\n\n").arg(readiness);

    if (readiness < 40) {
        return plan + "🚨 КРИТИЧЕСКИЙ УРОВЕНЬ: Организм истощен.\nРекомендуется полный отдых, легкая растяжка или прогулка.\n";
    }

    if (sleep >= 7) plan += "Сон отличный. Нервная система восстановлена.\n";
    else plan += "⚠️ Недосып. Снижен рабочий вес и количество подходов.\n";

    if (cals >= 2000) plan += "Энергии достаточно для интенсивной силовой работы.\n";
    else if (cals >= 1500) plan += "⚠️ Средний уровень энергии. Держите умеренный темп.\n";
    else plan += "⚠️ Дефицит калорий. Тренировка сокращена.\n";

    if (meal == 0) plan += "Вы только что поели. Исключены упражнения на пресс.\n";
    else if (meal >= 1 && meal <= 3) plan += "Идеальное время после приема пищи.\n";
    else plan += "Прошло много времени после еды, возможна слабость.\n";

    plan += "\n📋 --- ПРОГРАММА ---\n";

    QStringList targetGroups = manualGroups;
    
    if (isAuto) {
        int day = date.dayOfWeek();
        
        if (day == 1) { 
            targetGroups = {"Грудь", "Плечи", "Трицепс Плечи (Зад)"};
        } 
        else if (day == 3) { 
            targetGroups = {"Спина", "Руки", "Пресс"};
        } 
        else if (day == 5) { 
            targetGroups = {"Квадрицепс", "Задняя пов. бедра", "Ягодицы", "Икры"};
        } 
        else { 
            targetGroups = {"Грудь", "Спина", "Руки", "Квадрицепс"};
        }
    }

    int sets = (goal == 0) ? 4 : 3;
    if (cals < 1800) sets = std::max(2, sets - 1); 
    int reps = (goal == 0) ? 8 : 12;

    std::mt19937 g(date.toJulianDay());
    bool justAte = (meal == 0);

    for (const QString& group : targetGroups) {
        if (justAte && group == "Пресс") continue;
        plan += "\n[" + group + "]\n";
        
        std::vector<Exercise> currentGroupEx;
        for (const auto& ex : EXERCISE_DB) {
            if (ex.group == group) currentGroupEx.push_back(ex);
        }
        
        std::shuffle(currentGroupEx.begin(), currentGroupEx.end(), g);
        
        int count = 0;
        int maxEx = (sleep < 7) ? 2 : 3; 
        
        for (const auto& ex : currentGroupEx) {
            plan += QString("💪 %1: %2x%3\n").arg(ex.name).arg(sets).arg(reps);
            if (++count >= maxEx) break;
        }
    }
    return plan;
}